  function flatten(groups) {
    return groups.flat().map(([term, definition, analogy, application, subject], index) => ({
      id: index + 1,
      term,
      definition,
      analogy,
      application,
      subject,
      group: Math.floor(index / 5),
    }));
  }

  function rotate(items, amount) {
    const offset = amount % items.length;
    return items.slice(offset).concat(items.slice(0, offset));
  }

  function buildQuestion(concepts, concept, setNumber, level) {
    const group = concepts.filter((item) => item.group === concept.group);
    const distractors = group.filter((item) => item.id !== concept.id).slice(0, 3);
    const candidates = [concept, ...distractors];
    const questionTypes = [
      {
        stem: `下列哪一個名詞最符合這段定義？「${concept.definition}」`,
        clue: `題幹直接描述「${concept.term}」的核心定義。`,
      },
      {
        stem: `下列哪一個概念最符合這個類比？「${concept.analogy}」`,
        clue: `類比中的功能對應「${concept.term}」。`,
      },
      {
        stem: `某組織希望進行以下工作：「${concept.application}」。最直接相關的概念為何？`,
        clue: `此實務情境主要運用「${concept.term}」。`,
      },
    ];
    const rotated = rotate(candidates, (concept.id + setNumber) % candidates.length);
    const answerIndex = rotated.findIndex((item) => item.id === concept.id);
    const type = questionTypes[setNumber - 1];

    return {
      id: `${level}-${setNumber}-${String(concept.id).padStart(2, '0')}`,
      number: concept.id,
      level,
      subject: concept.subject,
      examPoint: concept.term,
      stem: type.stem,
      options: rotated.map((item) => item.term),
      answerIndex,
      correctReason: `${type.clue}${concept.definition}。實務例子：${concept.application}；可以把它想成「${concept.analogy}」。`,
      optionExplanations: rotated.map((item) => item.id === concept.id
        ? `正確。${concept.term}是${concept.definition}。`
        : `不正確。${item.term}是${item.definition}；本題線索指向${concept.term}，兩者的任務與使用時機不同。`),
    };
  }

  function buildExams(level, label, groups) {
    const concepts = flatten(groups);
    const focuses = level === 'beginner'
      ? ['概念定義辨識', '白話類比判斷', '實務情境應用']
      : ['技術原理辨識', '模型與資料類比', '系統情境應用'];

    return [1, 2, 3].map((setNumber) => ({
      id: `${level}-${setNumber}`,
      level,
      levelLabel: label,
      setNumber,
      title: `${label}模擬考第 ${setNumber} 份`,
      focus: focuses[setNumber - 1],
      questionCount: 50,
      questions: concepts.map((concept) => buildQuestion(concepts, concept, setNumber, level)),
    }));
  }

